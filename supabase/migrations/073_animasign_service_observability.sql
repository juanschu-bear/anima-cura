CREATE TABLE IF NOT EXISTS animasign_service_health (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checked_at timestamptz NOT NULL DEFAULT now(),
  healthy boolean NOT NULL,
  http_status integer,
  service_status text,
  database_status text,
  certificate_status text,
  response_ms integer NOT NULL,
  detail text
);

CREATE INDEX IF NOT EXISTS idx_animasign_service_health_checked_at
  ON animasign_service_health (checked_at DESC);

ALTER TABLE animasign_service_health ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS animasign_service_health_service_role ON animasign_service_health;
CREATE POLICY animasign_service_health_service_role ON animasign_service_health
  FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE TABLE IF NOT EXISTS animasign_service_errors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  operation text NOT NULL,
  http_status integer,
  response_text text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_animasign_service_errors_occurred_at
  ON animasign_service_errors (occurred_at DESC);

ALTER TABLE animasign_service_errors ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS animasign_service_errors_service_role ON animasign_service_errors;
CREATE POLICY animasign_service_errors_service_role ON animasign_service_errors
  FOR ALL TO service_role USING (true) WITH CHECK (true);

REVOKE ALL ON TABLE animasign_service_health FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE animasign_service_errors FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE animasign_service_health TO service_role;
GRANT ALL ON TABLE animasign_service_errors TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
